/**
 * يوم جهاز المندوب بصيغة YYYY-MM-DD.
 *
 * **لا `toISOString().slice(0,10)`**: تلك تعطي يوم UTC، ومنتصف ليل UTC ثلاثةٌ
 * فجراً بالرياض — فكل ما يُكتب بين التاسعة مساءً ومنتصف الليل بتوقيت المندوب
 * يُنسب إلى الغد. وتقريرٌ يومُه خطأ يصطدم بالقيد الفريد أو يُنشئ تقريراً
 * ثانياً ليومٍ واحد.
 *
 * مستقلٌّ في ملفّه بلا استيراد واحد: الشاشة تسحب عميل الـAPI معها، وعميلُ
 * الـAPI يقرأ متغيّرات بيئة Vite غير الموجودة في node:test — فيُصبح حارسُ
 * التاريخ غير قابل للاختبار وهو أولى ما يُختبَر.
 */
export function deviceDay(d = new Date()): string {
  const p = (n: number) => String(n).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

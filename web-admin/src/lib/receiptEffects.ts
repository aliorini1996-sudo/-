// ----------------------------------------------------------------------------
// الخلل الذي وُلد من غيابه: إصدار سندٍ وتوزيعه على الفواتير كان يُبطل
// `['receipts']` وحده، فتبقى قائمة الفواتير على نسختها المخزّنة وتعرض الفاتورة
// **غير مدفوعة ومبلغها كاملٌ في المتبقّي** بينما الخادم سدّدها فعلاً. والمستخدم
// يرى رقماً ماليّاً خاطئاً ولا شيء في الشاشة يقول إنّه قديم.
//
// ولماذا قائمةٌ معلنة لا سطرٌ في كل شاشة: مواضع إصدار السند وإلغائه أربعة
// (لوحة الويب، وقائمة مستندات الجوال، وشاشة الإصدار في الجوال، وملفّ العميل)،
// وإضافةُ شاشةٍ خامسة غداً ستنسى مفتاحاً. القائمة هنا تُقرأ مرّة ويُحرسها اختبار.
//
// وإبطال مفتاحٍ لا وجود له في الذاكرة **لا يكلّف شيئاً**: react-query يتجاهله.
// فالقائمة تجمع فضاءي الأسماء — لوحة الويب وتطبيق الجوال (`m-`) — بلا ضرر.
// ============================================================================

/** أقلّ ما نحتاجه من `QueryClient` — يجعل الدالّة قابلةً للاختبار بلا react */
export interface Invalidator {
  invalidateQueries: (opts: { queryKey: readonly unknown[] }) => unknown;
}

/**
 * كل استعلامٍ تتغيّر إجابته بإصدار سند قبض أو إلغائه.
 *
 * السند يغيّر ثلاثة أشياء على الخادم: مدفوع الفاتورة ومتبقّيها، ورصيد العميل،
 * وأرقام لوحة التحكّم. فكل شاشةٍ تعرض واحداً منها مذكورةٌ هنا.
 */
export const RECEIPT_TOUCHES: readonly (readonly string[])[] = [
  // ═══ لوحة الويب ═══
  ['receipts'],
  ['invoices'],      // المدفوع والمتبقّي — هو بيت الخلل الأصليّ
  ['customers'],     // رصيد العميل ومديونيته
  ['dashboard'],
  // ═══ تطبيق الإدارة على الجوال ═══
  ['m-docs', 'receipt'],
  ['m-docs', 'invoice'],
  ['m-rcp-invoices'], // الفواتير المفتوحة في شاشة الإصدار نفسها
  ['m-customers'],
  ['m-customer'],
  ['m-dashboard'],
];

/** يُبطل كل ما يمسّه السند. يُستدعى بعد نجاح الإصدار أو الإلغاء. */
export function invalidateAfterReceipt(qc: Invalidator): void {
  for (const queryKey of RECEIPT_TOUCHES) qc.invalidateQueries({ queryKey });
}

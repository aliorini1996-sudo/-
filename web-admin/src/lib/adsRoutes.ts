/** بادئات اللغة على الموقع التسويقي — الصفحة نفسها بلغة أخرى */
const LOCALE_PREFIX = /^\/(en|fr|tr|zh)(?=\/|$)/;

/** الجزء الأول من مسار الصفحة التسويقية (بعد نزع بادئة اللغة) */
const MARKETING_ROOTS = new Set([
  'about', 'terms', 'service-agreement', 'privacy', 'contact', 'subscribe-request',
  'calculator', 'invoice-generator', 'pricing', 'signup', 'tutorial', 'profile',
  'blog', 'free', 'قطاعات', 'مزايا', 'نماذج',
]);

/** أقسام لها صفحات فرعية بمستوى واحد (`/blog/:slug` · `/free/:tool` …) */
const WITH_CHILD = new Set(['blog', 'free', 'قطاعات', 'مزايا', 'نماذج']);

/**
 * هل يُسمح بوسم الإعلانات على هذا المسار؟
 *
 * الفكّ (`decodeURIComponent`) إلزامي: `location.pathname` يصل مُرمَّزاً للمسارات
 * العربية (`/%D9%82…`)، وبلا فكّه لا تطابق `/قطاعات` أبداً فتسقط صفحات القطاعات
 * والمزايا والنماذج من القائمة بصمت.
 */
export function isAdsTagRoute(pathname: string | null | undefined): boolean {
  let p = String(pathname || '/').split(/[?#]/)[0];
  try { p = decodeURIComponent(p); } catch { return false; } // ترميز تالف ⇒ لا وسم
  const segs = p.replace(LOCALE_PREFIX, '').split('/').filter(Boolean);
  if (segs.length === 0) return true; // الصفحة الرئيسية بأي لغة
  const [root, ...rest] = segs;
  if (!MARKETING_ROOTS.has(root)) return false;
  if (rest.length === 0) return true;
  return rest.length === 1 && WITH_CHILD.has(root);
}

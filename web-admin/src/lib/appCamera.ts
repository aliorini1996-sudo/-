export function cameraCaptureCrashes(ua: string = typeof navigator !== 'undefined' ? navigator.userAgent : ''): boolean {
  return /\sFieldSalesAdmin(?:\s|$)/.test(ua ?? '') && !/\sFSCam\/\d+(?:\s|$)/.test(ua ?? '');
}

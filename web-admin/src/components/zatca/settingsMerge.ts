/**
 * دمج تحديث بيانات الشركة من الخادم مع نموذج «الإعدادات العامة» المفتوح — صغير ومستقلّ عن منطق التبويب كي لا يُحمَّل
 * منطق ربط الفوترة في صفحة الإعدادات لكل الشركات.
 *
 * السبب: حفظ «بيانات المنشأة» في تبويب الفوترة الإلكترونية يُحدِّث ['company'] (الرقم الضريبي والسجل التجاري مشتركان مع
 * النموذج العام)، وكانت الصفحة تعيد ضبط كل الحقول عند أي تحديث فتمحو تعديلات غير محفوظة (شعار، لون، اسم، سرّ الربط…).
 */

/**
 * applied = آخر قيم طُبّقت من الخادم، next = القيم الجديدة، local = ما في النموذج الآن. الحقل الذي عدّله المستخدم
 * (يختلف عن applied) يبقى كما هو، وغيره يأخذ الجديد. applied = null (أول تحميل) ⇒ next كاملاً.
 */
export function keepLocalEdits<T extends object>(applied: T | null, next: T, local: T): T {
  if (!applied) return next;
  const out = { ...next };
  for (const k of Object.keys(next) as Array<keyof T>) {
    if (!Object.is(local[k], applied[k])) out[k] = local[k];
  }
  return out;
}

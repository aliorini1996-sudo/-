/**
 * قدرات هذه الحزمة كما تُعلنها للخادم — ترويسة واحدة على كل نداء.
 *
 * ZATCA المرحلة الثانية (Z5.2، نقد الخطة 1 و2): الخادم يردّ **426** على إصدار فاتورة أو قراءة فاتورة مختومة من حزمة لا
 * تحمل `zatca2`، لأن الحزمة القديمة تبني رمز QR للمرحلة الأولى بخمس وسوم من إعدادات الشركة وتطبع «فاتورة ضريبية» غير
 * مختومة. فالترويسة تُرسَل من **كلّ** عملاء المنصّة في الإصدار نفسه: لوحة الإدارة و`/m` (`api/client.ts`) وتطبيق المندوب
 * (`rep/repApi.ts` — نسخة axios مستقلّة) — وإلا خرجت اللوحة و`/m` من الخدمة يوم التفعيل بينما يعمل المندوب وحده.
 *
 * القائمة مفصولة بفواصل ويقرأها الخادم رمزاً رمزاً، فإضافة قدرة لاحقاً لا تكسر القديم.
 */
export const FS_CAPS_HEADER = 'X-FS-Caps';

/** فواتير المرحلة الثانية: الحزمة تفهم `einvoice` في الردّ، ولا تُصدر مستنداً ضريبياً دون اتصال (D1‑i). */
export const CAP_ZATCA2 = 'zatca2';

export const FS_CAPS: readonly string[] = Object.freeze([CAP_ZATCA2]);

/** قيمة الترويسة كما تُرسَل. */
export const FS_CAPS_VALUE = FS_CAPS.join(',');

/** هل تُعلن هذه القيمة قدرةً بعينها؟ (القراءة نفسها التي يجريها الخادم — للاختبار وللتشخيص) */
export function capsInclude(value: string | null | undefined, cap: string): boolean {
  return typeof value === 'string' && value.split(/[,\s;]+/).some(t => t.trim().toLowerCase() === cap.toLowerCase());
}

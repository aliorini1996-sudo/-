/**
 * أيّ مصدرٍ لموقع العميل يُكتب حين يحمل طلب **الإنشاء** إحداثياتٍ صريحة ورابطاً معاً (تدقيق البصمة PIN-3، ٧ نوفمبر ٢٠٢٦ —
 * قرار المالك «أصلح الخلل فقط»).
 *
 * شاشة إضافة العميل في تطبيق المندوب كانت ترسل التقاط GPS عند الباب والرابط الملصوق معاً، وكان الخادم يحلّ الرابط ويكتبه
 * فوق الالتقاط — ورابط Google قد يحمل مركز الخريطة لا دبّوس المحلّ، فيُزاح العميل مئات الأمتار وتُرفض بعده بصمةٌ
 * صادقة عند بابه. الآن: lat وlng رقمان معاً ⇒ تُقدَّم الصريحة ولا يُحلّ الرابط أصلاً (ويشمل رفعاً مؤجَّلاً من صندوق
 * المندوب بنسخةٍ قديمة من التطبيق).
 *
 * والتعديل (PUT) خارج هذا عمداً: الرابط فيه مقدَّمٌ كما كان — نموذج الإدارة يعيد إحداثيات صفّه مع الرابط الجديد، وصفٌّ
 * قديم كان سيُسقط الرابط الملصوق ويكتب فوق التقاطٍ أحدث. وما سوى ذلك كما كان حرفياً: رابطٌ وحده، أو مع إحداثيةٍ واحدة،
 * أو مع null، يُحلّ ويكتب فوقها. و(0،0) معاً ليست التقاطاً بل قيمةٌ فارغة يرسلها تكاملٌ بلا إحداثيات — فالرابط يُحلّ
 * كما كان. ولا يمسّ شيئاً مما يقبله الخادم أو يرفضه.
 */

const finite = (n: unknown): n is number => typeof n === 'number' && Number.isFinite(n);

export interface SentPin { lat?: number | null; lng?: number | null }

/** true ⇒ في الإنشاء تُكتب الإحداثيات الصريحة ويُتجاهل locationUrl المرافق لها (لا يُحلّ) */
export function explicitPinWins(sent: SentPin): boolean {
  if (!finite(sent.lat) || !finite(sent.lng)) return false;
  // (0،0) معاً = خانةٌ فارغة من تكامل (خليج غينيا لا محلّ فيه) — الرابط المرافق هو الموقع المقصود
  return !(sent.lat === 0 && sent.lng === 0);
}

export interface Plan {
  id: string;
  name: string;
  priceSar: number;
  note?: string;
}

/** التسعير المعتمد — لكل شركة لا لكل مستخدم (تمايزنا المسوَّق) */
export const PLANS: Plan[] = [
  { id: 'basic', name: 'الباقة المبتدئة', priceSar: 299, note: 'حتى ٥ مناديب ومستخدم إداري واحد — شاملة الضريبة' },
  { id: 'growth', name: 'الباقة المتوسطة', priceSar: 399, note: 'حتى ١٠ مناديب ومستخدمَين إداريَّين — شاملة الضريبة' },
  { id: 'pro', name: 'الباقة المتقدّمة', priceSar: 599, note: 'حتى ٢٠ مندوباً و٥ مستخدمين إداريين — شاملة الضريبة' },
];

/** العرض الترويجي الحالي — يُطفأ بتغيير active إلى false، ولا شيء آخر */
export const OFFER = {
  /**
   * **مُطفأ بقرار المالك (١٠ سبتمبر ٢٠٢٦)** مع اعتماد الباقات الثلاث.
   *
   * كان يناقض التسعير المعلن: الموقع يسعّر لكل شركة والبوت يقتبس ٢٠ ريالاً
   * لكل مندوب. وبوتٌ ينطق سعراً يُلزم الشركة قانوناً (سابقة Air Canada)،
   * فتناقضُ مصدرين على الزبون نفسه مخاطرةٌ لا تُحتمل.
   */
  active: false,
  id: 'september-2026',
  name: 'عرض سبتمبر',
  pricePerRepSar: 20,
  endsAt: '2026-09-30',
  endsAtLabel: '30 سبتمبر',
} as const;

/** التجربة المجانية — الوعد الوحيد المسموح بشأن التفعيل */
export const TRIAL = { days: 10, requiresCard: false } as const;

/** السطر الوحيد المسموح لوصف العرض */
export function offerLine(): string {
  if (!OFFER.active) return '';
  return `${OFFER.name}: ${OFFER.pricePerRepSar} ريال لكل مندوب شهرياً — ساري حتى ${OFFER.endsAtLabel}`;
}

/** حساب تكلفة فريق العميل بالعرض الحالي */
export function priceForReps(reps: number): number {
  if (!OFFER.active) return PLANS[0].priceSar;
  return Math.max(0, Math.round(reps)) * OFFER.pricePerRepSar;
}

/** كل الأرقام المالية المسموح ظهورها في ردّ البوت */
export function allowedMoneyValues(maxReps = 200): Set<number> {
  const set = new Set<number>();
  PLANS.forEach((p) => set.add(p.priceSar));
  set.add(OFFER.pricePerRepSar);
  set.add(TRIAL.days);
  // حواصل ضرب العرض لأحجام الفرق المعقولة (البوت يحسب تكلفة الفريق)
  for (let r = 1; r <= maxReps; r++) set.add(r * OFFER.pricePerRepSar);
  return set;
}

// ——— ادّعاءات ZATCA ———
// ربط المرحلة الثانية مع منصة فاتورة صار قدرة معلنة (قرار المالك بعد التفعيل الفعلي)، فلا يُحجب
// ذكره. الممنوع ولو بعد التفعيل: الاعتماد/المصادقة/الترخيص من الهيئة، والشراكة الرسمية، وأي موعد أو رقم.
// ⚠️ يتّسق مع حارس الموقع (web-admin/scripts/claims-rules.mjs) — اختبار wa-agent-guard.test.ts يمرّر
// الجمل نفسها على الحارسين. كانت هذه الأنماط تمرّر «منذ يناير وإحنا ندعم…» (الموعد قبل المصطلح)،
// و«الموجة ٢٥» (\d لاتيني فقط)، و«٤٠ شركة»، و«المرحله الثانيه»، و«معتمد في منصة فاتورة» و«من قبل الهيئة».
// النص يُفحص بتشكيله وبلا تشكيل (guard.ts)، فالأنماط بلا تشكيل.
const AR_LETTER = '\\u0600-\\u06FF';
/** المرحلة الثانية: «للمرحلة» (اللام تُسقط ألف ال) و«المرحله الثانيه» (التاء هاءً) */
const P2 = '(?:(?:ال|لل)مرحل[ةه]\\s*(?:الثاني[ةه]|٢|2)|phase\\s*(?:2|II|two)\\b)';
/** جهة الادّعاء: الهيئة أو منصتها */
const ZATCA_BODY = '(?:هيئ[ةه]|الهيئ[ةه]|الزكا[ةه]|زاتكا|ZATCA|منص[ةه]\\s*«?فاتور[ةه])';
/** موعد أو رقم — عربي وهندي، قبل المصطلح وبعده */
const P2_DATE = [
  'منذ|بحلول|اعتبارا|ابتداء|من\\s*سن[ةه]',
  'خلال\\s*(?:[\\d٠-٩]+|أيام|ايام|يوم|ساعات|ساعة|أسابيع|اسابيع|أسبوع|دقائق|دقيقة|أشهر|اشهر|شهر)',
  '(?:19|20)\\d{2}|[١٢][٠٩][٠-٩]{2}|(?<![\\d٠-٩])(?:1[34]\\d{2}|١[٣٤][٠-٩]{2})(?![\\d٠-٩])',
  '(?:ال)?موج[ةه]\\s*[\\d٠-٩]+|\\bwave\\s*\\d+',
  `(?<![${AR_LETTER}])(?:يناير|فبراير|مارس|أبريل|ابريل|إبريل|مايو|يونيو|يوليو|أغسطس|اغسطس|سبتمبر|أكتوبر|اكتوبر|نوفمبر|ديسمبر|محرم|رجب|شعبان|رمضان|شوال)(?![${AR_LETTER}])`,
  '\\b(?:since|as\\s+of|by|in|from|until|before)\\s+(?:January|February|March|April|May|June|July|August|September|October|November|December|\\d)|\\bsince\\b',
  `قريبا(?!\\s*من)|\\bsoon\\b|(?<![${AR_LETTER}])(?:سن|ست|سي|سوف\\s*[نتي])(?:دعم|ربط|وفر|فعل)`,
  '[\\d٠-٩][\\d٠-٩,.٬]*\\s*\\+?\\s*(?:شرك[ةه]|شركات|عميل|عملاء|منشأ[ةه]|منشآت|مؤسس[ةه]|مؤسسات|تاجر|تجار|موزع|موزعين|فاتور[ةه]|فواتير|companies|customers|clients|businesses)',
  `(?<![${AR_LETTER}])[وبل]?(?:مئات|عشرات|آلاف|الاف)(?![${AR_LETTER}])`,
  '(?<![\\d٠-٩])(?:100|١٠٠)\\s*[%٪]',
].join('|');


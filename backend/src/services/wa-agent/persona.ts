/** رسالة الترحيب الأولى — تُرسل فوراً بلا انتظار النموذج (سرعة الرد أهم) */
export function instantGreeting(dialect: Dialect, offerActive = OFFER.active): string {
  const offer = offerActive ? `\nعندنا الحين ${offerLine()} 🎯` : '';
  switch (dialect) {
    case 'gulf':
      return `هلا والله ومرحبا فيك 🙌\nمعك مساعد Field Sales — منصّة إدارة المبيعات الميدانية والتوزيع.${offer}\nكم مندوب عندك تقريباً؟`;
    case 'egypt':
      return `أهلاً بيك ومرحب 🙌\nأنا مساعد Field Sales — منصة إدارة المبيعات الميدانية والتوزيع.${offer}\nعندك كام مندوب تقريباً؟`;
    case 'levant':
      return `أهلين وسهلين فيك 🙌\nأنا مساعد Field Sales — منصّة إدارة المبيعات الميدانية والتوزيع.${offer}\nكم مندوب عندك تقريباً؟`;
    default:
      return `أهلاً وسهلاً بك 🙌\nأنا مساعد Field Sales — منصّة إدارة المبيعات الميدانية والتوزيع.${offer}\nكم مندوباً لديك تقريباً؟`;
  }
}

/** ملخّص التسليم الدافئ للمالك عند التصعيد */
export function handoffSummary(input: {
  waId: string;
  name?: string;
  reason: string;
  repCount?: number;
  transcript: { role: 'customer' | 'agent'; text: string }[];
}): string {
  const last = input.transcript.slice(-6).map((m) => `${m.role === 'customer' ? '👤' : '🤖'} ${m.text}`).join('\n');
  const price = input.repCount ? `\n💰 التكلفة بالعرض: ${priceForReps(input.repCount)} ريال/شهر` : '';
  return [
    `🔔 عميل يحتاجك — ${input.name || input.waId}`,
    `📱 ${input.waId}`,
    `📌 السبب: ${input.reason}`,
    input.repCount ? `👥 عدد المناديب: ${input.repCount}` : '',
    price,
    '',
    'آخر ما دار:',
    last,
  ].filter(Boolean).join('\n');
}

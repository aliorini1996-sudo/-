/** اللهجة تُستنتج من كود الدولة في رقم واتساب الوارد */
export type Dialect = 'gulf' | 'egypt' | 'levant' | 'maghreb' | 'msa';

export function dialectFromPhone(waId: string): Dialect {
  const n = waId.replace(/\D/g, '');
  if (/^(966|971|965|973|974|968)/.test(n)) return 'gulf';
  if (/^20/.test(n)) return 'egypt';
  if (/^(962|963|961|970|972|964)/.test(n)) return 'levant';
  if (/^(212|213|216|218)/.test(n)) return 'maghreb';
  return 'msa';
}


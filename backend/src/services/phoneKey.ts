/**
 * مفتاح الجوال — **هوية بوابة واتساب نفسها** (routes/waAccount.ts يطابق به رقم المرسِل الموثّق مع
 * `CompanySettings.phone`). نُقل إلى هنا كما هو حرفاً بحرف ليكون مصدراً واحداً لكلّ فحص «هل هذا الجوال
 * مربوطٌ بشركةٍ أخرى؟»: مقارنةٌ بمطبِّعٍ غير الذي تُحدَّد به الهوية كانت ستُجيز رقماً تراه البوابة
 * مطابقاً لشركةٍ قائمة — فتصير غامضةً (تطابقان) ويتوقّف واتساب العميل الحقيقي.
 *
 * أرقام فقط، وتوحيد الصيغ المحلية الخليجية الشائعة إلى الدولية (05x ⇒ 9665x).
 */
export function phoneKey(v: string | null | undefined): string {
  let d = String(v || '').replace(/[^\d]/g, '');
  if (d.startsWith('00')) d = d.slice(2);
  if (d.length === 10 && d.startsWith('05')) d = '966' + d.slice(1); // سعودي محلي
  if (d.length === 9 && d.startsWith('5')) d = '966' + d;            // بلا صفر
  return d;
}

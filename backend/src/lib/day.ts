/**
 * يومٌ تقويميّ بصيغة `YYYY-MM-DD` — الوحدة التي تُقاس بها أيّام هذا النظام.
 *
 * التواريخ اليوميّة في المنصّة **نصٌّ لا DateTime** (اقرأ تعليق `reportDate`
 * في المخطّط): القيد الفريد يجب أن يطابق «اليوم» مطابقةً حرفية، وDateTime
 * بإزاحةٍ مختلفة يولّد صفَّين ليومٍ واحد. وثمن ذلك أنّ كلّ تحقّقٍ يقع على
 * النصّ، ونصٌّ بشكل تاريخ ليس تاريخاً.
 */

/**
 * هل هذا النصّ يومٌ **موجودٌ في التقويم**؟
 *
 * `^\d{4}-\d{2}-\d{2}$` وحده يقبل «2026-13-01» و«2026-02-30»، وهما يفترقان في
 * الضرر افتراقاً تامّاً:
 *  - الأوّل تُعيد له `Date.parse` قيمة NaN، فينهار `new Date(NaN).toISOString()`
 *    بـRangeError — أي ردّ ٥٠٠ على مدخلٍ خاطئ حقّه ٤٠٠.
 *  - والثاني يُقرأ **أوّل مارس بصمت**، فيرى المستخدم مدّةً غير التي طلب ولا
 *    شيء يخبره.
 * والذهاب والإياب (تحليلٌ ثمّ إعادة تسلسل ومقارنة حرفية) هو الفحص الوحيد الذي
 * يلتقط الاثنين معاً.
 */
export function isCalendarDay(date: string): boolean {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(date)) return false;
  const t = Date.parse(`${date}T00:00:00.000Z`);
  return Number.isFinite(t) && new Date(t).toISOString().slice(0, 10) === date;
}
